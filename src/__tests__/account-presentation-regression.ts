import assert from 'node:assert/strict';
import { accountPresentation } from '../lib/accountPresentation';
import { DEMO_TRIAL_CUSTOMER, DEMO_PAID_CUSTOMER, type CustomerProfile } from '../context/CustomerAuthContext';
const fresh = structuredClone(DEMO_TRIAL_CUSTOMER);
fresh.trial = { ...fresh.trial, status: 'not_started', startDate: null, endDate: null };
fresh.subscription = { ...fresh.subscription, status: 'none', renewsAt: null };
fresh.licenses = []; fresh.trialEndsAt = ''; fresh.nextBillingDate = '';
assert.equal(accountPresentation(fresh).status, 'No active plan');
assert.equal(accountPresentation(fresh).date, 'Not available', 'Missing expiry must not be replaced by an invented future date');
const ended: CustomerProfile = { ...fresh, accountStatus: 'trial_expired', trial: { ...fresh.trial, status: 'expired', endDate: new Date(Date.now() - 86400000).toISOString() } };
assert.equal(accountPresentation(ended).status, 'Trial ended', 'Expired trial must not appear active');
const trial = { ...fresh, accountStatus: 'trial_active', trial: { ...fresh.trial, status: 'active', startDate: new Date().toISOString(), endDate: new Date(Date.now() + 3 * 86400000).toISOString(), daysRemaining: 7 } } as CustomerProfile;
assert.equal(accountPresentation(trial).status, 'Trial · 3 days left', 'Countdown must use the saved end date, not a stale display value');
const paid = structuredClone(DEMO_PAID_CUSTOMER);
paid.currency = 'USD'; paid.plan = 'Business';
paid.subscription = { ...paid.subscription, status: 'active', planId: 'Business', renewsAt: new Date(Date.now() + 30 * 86400000).toISOString() };
paid.licenses = [];
assert.equal(accountPresentation(paid).price, '$400');
assert.equal(accountPresentation(paid).status, 'Active plan');
paid.connectedStore = { name: 'Demo', status: 'pending', url: 'https://shop.example.invalid' };
assert.equal(accountPresentation(paid).connected, false, 'A supplied URL alone is not a confirmed connection');
paid.connectedStore.status = 'connected';
assert.equal(accountPresentation(paid).connected, true);
paid.subscription.status = 'expired'; paid.subscription.renewsAt = new Date(Date.now() - 86400000).toISOString(); paid.accountStatus = 'expired';
assert.equal(accountPresentation(paid).status, 'Plan expired');
console.log('PASS: account labels, real expiry dates, date-based trial countdown, USD pricing and confirmed connection state.');
